# Video 3: proceso completo de Cámbiate a nivelado (PC y celular)
import sys, datetime
from playwright.sync_api import sync_playwright
from engine import Escena
from backend import Demo
from compose import armar

demo = Demo()
solo = sys.argv[1:]
manana = (datetime.datetime.utcnow() - datetime.timedelta(hours=6) + datetime.timedelta(days=1)).strftime('%Y-%m-%d') + 'T10:00'

with sync_playwright() as pw:
    if not solo or 'pc' in solo:
        demo.reset()
        e = Escena(pw, demo, 'v3_pc', 'pc', sesion=True, appmode=True); e.iniciar()
        e.decir('Para trabajar la campaña, toque Cámbiate a nivelado en el menú.')
        e.pausa(1.5)
        e.tocar('#sideNav [data-nk="nivelado"]')
        e.decir('Aquí están los clientes de su cartera que tienen préstamo solo interés y pueden pasarse a nivelado: los que tienen un año o más, o seis meses o más sin abonar a capital.')
        e.señalar('.mt-hdr h2'); e.pausa(3.5)
        e.señalar('.nv-kpis')
        e.decir('Arriba ve su avance: cuántos clientes aplican, cuántos ha gestionado, cuántos aceptaron y cuántos ya se cambiaron a nivelado.')
        e.señalar('.nv-kpis .mt-kpi', n=0); e.pausa(1.3)
        e.señalar('.nv-kpis .mt-kpi', n=1); e.pausa(1.3)
        e.señalar('.nv-kpis .mt-kpi', n=3); e.pausa(1.3)
        e.señalar('.nv-kpis .mt-kpi', n=5)
        e.decir('Las pestañas separan a los clientes. Para hoy tiene las llamadas que programó para hoy. Sin gestionar, los que todavía no ha llamado.')
        e.señalar('[data-nvv="hoy"]'); e.pausa(2.6)
        e.tocar('[data-nvv="pendiente"]')
        e.decir('Cada tarjeta muestra el préstamo del cliente: el capital, los intereses acumulados, la mora y el total que debe.')
        e.señalar('[data-nv="501"] .mt-meta', n=1)
        e.decir('Para trabajar un cliente, toque Gestionar.')
        e.tocar('[data-nvg="501"]')
        e.pausa(1.0)
        e.decir('Se abre su vista completa. A la izquierda está el préstamo actual y el total adeudado. Llame al cliente al número que aparece aquí.')
        e.señalar('.nv-vista .nv-tot-c'); e.pausa(2.5)
        e.señalar('#nvTelV a', n=0)
        e.decir('Si el cliente no contesta o le pide que lo llame después, márquelo a la derecha y elija la fecha y la hora. El sistema se lo recuerda en Para hoy.')
        e.pausa(1.5)
        e.tocar('[data-nvr="volver_llamar"]')
        e.escribir('#nvNota', 'Está en el trabajo, llamarle mañana.', retardo=40)
        e.llenar('#nvSeg', manana)
        e.tocar('#nvGuardar')
        e.pausa(0.8)
        e.decir('Cuando vuelva a llamarle y el cliente acepte, toque Acepta el cambio y guarde.')
        e.pausa(1.2)
        e.tocar('[data-nvr="acepta"]')
        e.escribir('#nvNota', 'Le interesa pagar quincenal.', retardo=40)
        e.tocar('#nvGuardar')
        e.pausa(1.2)
        e.decir('Ahora arme el nuevo préstamo. Primero escriba la identidad del cliente.')
        e.escribir('#nvDniN', '0501198803214', retardo=80)
        e.pausa(0.8)
        e.decir('El monto ya viene con todo lo que debe. Si el cliente pide un poco más, puede cambiarlo.')
        e.señalar('#nvMontoN'); e.pausa(1.2)
        e.escribir('#nvMontoN', '24000', limpiar=True, retardo=110)
        e.decir('La tasa viene en catorce por ciento, que es la normal. Solo cámbiela si se lo autorizaron.')
        e.señalar('#nvTasaN')
        e.decir('En la tabla ve la cuota de cada plazo, quincenal y mensual. Toque la que elija el cliente.')
        e.señalar('#nvProy'); e.pausa(2.2)
        e.tocar('#nvProy [data-pl="10"][data-fr="Quincenal"]')
        e.decir('Con la identidad ya puede ver el contrato, para imprimirlo o descargarlo en PDF y enviárselo al cliente.')
        e.pausa(1.0)
        e.tocar('#nvCtB')
        e.pausa(2.0)
        e.señalar('.rd-wrap [data-a="pdf"]'); e.pausa(1.2)
        e.tocar('.rd-wrap [data-x]')
        e.decir('Con todo definido, toque Generar solicitud. Revise el resumen, confirme el teléfono, deje una nota si quiere y toque Enviar al asesor.')
        e.pausa(0.8)
        e.tocar('#nvGenB')
        e.señalar('.nv-res-s'); e.pausa(2.0)
        e.escribir('#nsNota', 'Prefiere pagar el 15 y el 30.', retardo=40)
        e.tocar('#nsOk')
        e.pausa(1.0)
        e.decir('Listo. La solicitud le llega al asesor como Cambio de modalidad, y aquí ve en qué paso va.')
        e.ver('.nv-vista .gp')
        e.señalar('.nv-vista .gp')
        e.decir('Cierre la vista con la flecha para volver a la lista.')
        e.tocar('.nv-vista .bar [data-x]')
        e.terminar(1.0)

    if not solo or 'mov' in solo:
        demo.reset()
        e = Escena(pw, demo, 'v3_mov', 'movil', 'Cámbiate a nivelado en el celular', sesion=True, appmode=True); e.iniciar()
        e.decir('En el celular, toque Nivelado en el menú de abajo. El número rojo son sus llamadas de hoy.')
        e.pausa(2.2)
        e.tocar('#botNav [data-nk="nivelado"]')
        e.decir('En Para hoy están las llamadas programadas. Toque al cliente para abrirlo.')
        e.ver('[data-nv="503"]')
        e.pausa(1.0)
        e.tocar('[data-nv="503"] .mt-nm')
        e.pausa(0.8)
        e.decir('Arriba ve su préstamo y el total que debe. Llámele desde aquí.')
        e.ver('.nv-vista .nv-tot-c'); e.pausa(1.5)
        e.señalar('#nvTelV a', n=0); e.soltar()
        e.decir('Si el cliente no está interesado, toque No le interesa y escriba el motivo. Ese motivo ayuda a mejorar la campaña.')
        e.pausa(1.2)
        e.tocar('[data-nvr="no_interesa"]')
        e.escribir('#nvNota', 'Va a cancelar su préstamo el próximo mes.', retardo=40)
        e.tocar('#nvGuardar')
        e.pausa(0.8)
        e.decir('La respuesta queda en el historial, con la fecha y quién la registró.')
        e.ver('.nv-hist'); e.pausa(1.5)
        e.decir('Para volver, toque la flecha.')
        e.tocar('.nv-vista .bar [data-x]')
        e.decir('Y con el buscador encuentra a cualquier cliente por su nombre.')
        e.app_js("window.scrollTo({top:0, behavior:'smooth'})"); e.pausa(0.8)
        e.tocar('[data-nvv="todos"]')
        e.escribir('#nvQ', 'Sonia', retardo=110)
        e.pausa(0.6)
        e.ver('#nvL .nv-c', bloque='center')
        e.pausa(2.0)
        e.terminar(1.0)

